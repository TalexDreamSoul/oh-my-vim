import test from 'node:test'
import assert from 'node:assert/strict'
import { VimEngine } from '../src/engine.js'

function engine(lines: string[], cursor = { row: 0, col: 0 }): VimEngine {
  return new VimEngine({ lines, cursor })
}

test('mode switching and insertion commands', () => {
  const e = engine(['cat'])
  assert.equal(e.state.mode, 'NORMAL')
  e.send('i')
  assert.equal(e.state.mode, 'INSERT')
  e.send('X')
  assert.deepEqual(e.state.buffer, ['Xcat'])
  e.send('Esc')
  assert.equal(e.state.mode, 'NORMAL')
  assert.equal(e.state.cursor.col, 0)
  e.send('a')
  assert.equal(e.state.mode, 'INSERT')
  e.send('Y')
  e.send('Esc')
  assert.deepEqual(e.state.buffer, ['XYcat'])
  e.send('o')
  assert.equal(e.state.mode, 'INSERT')
  e.send('z')
  e.send('Esc')
  assert.deepEqual(e.state.buffer, ['XYcat', 'z'])
})

test('count motions and operator count assembly', () => {
  const e = engine(['one two three four'])
  e.replay('3w')
  assert.equal(e.state.cursor.col, 14)
  assert.equal(e.state.pending, null)
  e.send('0')
  e.replay('d3w')
  assert.deepEqual(e.state.buffer, ['four'])
  assert.equal(e.state.registers[''], 'one two three ')
  const lines = engine(['a', 'b', 'c', 'd'])
  lines.replay('2dd')
  assert.deepEqual(lines.state.buffer, ['c', 'd'])
  assert.equal(lines.state.cursor.row, 0)
  assert.equal(lines.state.pending, null)
})

test('operator text objects and registers', () => {
  const e = engine(['say "hello world" now'])
  e.replay('di"')
  assert.deepEqual(e.state.buffer, ['say "" now'])
  assert.equal(e.state.registers[''], 'hello world')
  const named = engine(['one two'])
  named.replay('"ayy')
  assert.equal(named.state.registers.a, 'one two\n')
  assert.equal(named.state.registers[''], 'one two\n')
})

test('register put and visual modes', () => {
  const e = engine(['alpha', 'beta', 'gamma'])
  e.replay('yyjp')
  assert.deepEqual(e.state.buffer, ['alpha', 'beta', 'alpha', 'gamma'])
  const visual = engine(['alpha', 'beta', 'gamma'])
  visual.send('V')
  assert.equal(visual.state.mode, 'VLINE')
  visual.send('j')
  visual.send('x')
  assert.deepEqual(visual.state.buffer, ['gamma'])
  assert.equal(visual.state.mode, 'NORMAL')
  const chars = engine(['abcd'])
  chars.replay('vlx')
  assert.deepEqual(chars.state.buffer, ['cd'])
})

test('replace, toggle, and insert line commands', () => {
  const e = engine(['abc'])
  e.replay('rZ')
  assert.deepEqual(e.state.buffer, ['Zbc'])
  e.send('~')
  assert.deepEqual(e.state.buffer, ['zbc'])
  e.replay('RXY<Esc>')
  assert.deepEqual(e.state.buffer, ['XYc'])
  const s = engine(['abc'])
  s.replay('sQ<Esc>')
  assert.deepEqual(s.state.buffer, ['Qbc'])
  const upper = engine(['abc'])
  upper.replay('SXYZ<Esc>')
  assert.deepEqual(upper.state.buffer, ['XYZ'])
})

test('undo and redo restore edits without throwing', () => {
  const e = engine(['one'])
  e.replay('iX<Esc>')
  assert.deepEqual(e.state.buffer, ['Xone'])
  e.send('u')
  assert.deepEqual(e.state.buffer, ['one'])
  assert.equal(e.state.mode, 'NORMAL')
  e.send('<C-r>')
  assert.deepEqual(e.state.buffer, ['Xone'])
  assert.equal(e.state.pending, null)
  const invalid = e.send('d')
  assert.ok(invalid.pending)
  const safe = e.send('!')
  assert.ok(Array.isArray(safe.buffer))
  assert.equal(safe.mode, 'NORMAL')
})

test('command line substitution and search repeat', () => {
  const e = engine(['cat dog cat', 'cat'])
  e.replay('/cat<Enter>')
  assert.equal(e.state.lastSearch, 'cat')
  assert.equal(e.state.cursor.col, 8)
  e.send('n')
  assert.equal(e.state.cursor.col, 0)
  e.send('N')
  assert.equal(e.state.cursor.col, 0)
  e.replay('*')
  assert.equal(e.state.lastSearch, 'cat')
  e.replay(':%s/cat/fox/g<Enter>')
  assert.deepEqual(e.state.buffer, ['fox dog fox', 'fox'])
  assert.equal(e.state.mode, 'NORMAL')
  assert.match(e.state.message ?? '', /替换/)
})

test('marks, find repeat, and replay notation', () => {
  const e = engine(['abcabc'])
  e.replay('mfll`f')
  assert.equal(e.state.marks.f.col, 0)
  assert.equal(e.state.cursor.col, 0)
  e.replay('fa;')
  assert.ok(e.state.cursor.col > 0)
  e.replay('"')
  assert.ok(e.state.pending)
  e.send('Esc')
  assert.equal(e.state.pending, null)
})
